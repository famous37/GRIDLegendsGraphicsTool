    private fun preset(
        name: String,
        description: String,
        fps: String,
        height: String,
        minPercent: String,
        maxPercent: String,
        dynamic: String,
        texture: String,
        aa: String,
        shadows: String,
        lod: String,
        ground: String,
        crowds: String,
        post: String,
        ssr: String,
        volumetrics: String,
        hdr: String,
        graphicsLevel: String,
        graphicsShadows: String,
        graphicsDynamic: String,
        graphicsOptimisation: String
    ): GraphicsPreset {
        val graphicsScalar = graphicsLevel.substringBefore(',').trim()
        val isExtreme = graphicsScalar.toIntOrNull()?.let { it >= 4 } == true
        val extremeOrConfigured = { configured: String -> if (isExtreme) "4" else configured }
        val values = mapOf(
            "FramerateLimit" to fps,
            "DynamicResolution" to extremeOrConfigured(dynamic),
            "TextureQuality" to extremeOrConfigured(texture),
            "AntiAliasing" to extremeOrConfigured(aa),
            "Shadows" to extremeOrConfigured(shadows),
            "LODQuality" to extremeOrConfigured(lod),
            "GroundCover" to extremeOrConfigured(ground),
            "Crowds" to crowds,
            "PostProcess" to extremeOrConfigured(post),
            "MotionBlur" to if (isExtreme) "4" else if (post == "2") "3" else "1",
            "ScreenSpaceReflections" to if (isExtreme) "4" else if (ssr == "3") "2" else "1",
            "VehicleReflections" to if (isExtreme) "4" else if (graphicsScalar == "3" && post == "2") "3" else "1",
            "SmokeShadows" to if (isExtreme) "4" else if (post == "2") "2" else "1",
            "VolumetricLights" to if (isExtreme) "4" else if (volumetrics == "3") "2" else "1",
            "FireworksAndConfetti" to if (isExtreme) "4" else if (post == "2") "3" else "1",
            "HDR" to hdr,
            "PresetOverride" to if (post == "2") "1" else "0",
            "DevicePreset" to if (post == "2") "1" else "0",
            "Setup/FixedScreenHeight" to height,
            "Setup/EnableSSR" to if (isExtreme) "4" else ssr,
            "Setup/EnableVolumetrics" to if (isExtreme) "4" else volumetrics,
            "Setup/EnableEdgeBlurOnQuarterRes" to if (height == "360") "0" else "1",
            "Graphics/FramerateLimit" to fps,
            "Graphics/FrameSizeMinimumPercentage" to minPercent,
            "Graphics/FrameSizeMaximumPercentage" to maxPercent,
            "Graphics/OptimisationResolutionMultiplier" to graphicsOptimisation,
            "Graphics/DynamicResolution" to if (isExtreme) "4, 0, 0" else graphicsDynamic,
            "Graphics/TextureQuality" to graphicsLevel,
            "Graphics/AntiAliasing" to graphicsLevel,
            "Graphics/Shadows" to if (isExtreme) "4, 0, 0" else graphicsShadows,
            "Graphics/LODQuality" to graphicsLevel,
            "Graphics/GroundCover" to graphicsLevel,
            "Graphics/Crowds" to when (crowds) {
                "0" -> "0, 0, 0"
                "1" -> if (graphicsScalar == "3") "2, 0, 0" else "1, 0, 0"
                else -> "1, 0, 0"
            },
            "Graphics/PostProcess" to if (isExtreme) "4, 0, 0" else if (post == "2") "3, 0, 0" else graphicsLevel,
            "Graphics/ScreenSpaceReflections" to if (isExtreme) "4, 0, 0" else if (ssr == "3") "3, 0, 0" else graphicsLevel,
            "Graphics/VehicleReflections" to if (isExtreme) "4, 0, 0" else graphicsLevel,
            "Graphics/VolumetricLights" to if (isExtreme) "4, 0, 0" else if (volumetrics == "3") "3, 0, 0" else "1, 0, 0",
            "Graphics/WeatherEffects" to graphicsLevel,
            "Graphics/Particles" to if (isExtreme) "4, 0, 0" else if (post == "2") "3, 0, 0" else "0, 0, 0",
            "Graphics/Mirrors" to if (isExtreme) "4, 0, 0" else if (graphicsScalar == "3") "3, 0, 0" else "0, 0, 0",
            "Graphics/LightingQuality" to graphicsLevel,
            "Graphics/SmokeShadows" to if (isExtreme) "4, 0, 0" else if (post == "2") "3, 0, 0" else "1, 0, 0",
            "Graphics/Skidmarks" to graphicsLevel,
            "Graphics/AmbientOcclusion" to graphicsLevel,
            "Performance/FramerateLimit" to if (fps == "60") "60" else "120",
            "Performance/FrameSizeMaximumPercentage" to if (fps == "60") "90" else "80",
            "Performance/OptimisationResolutionMultiplier" to if (fps == "60") "86" else "100",
            "Performance/LODQuality" to if (fps == "60") "1, 0, 0" else "2, 0, 0",
            "Performance/VehicleReflections" to if (fps == "60") "1, 0, 0" else "3, 0, 0",
            "Performance/CubeMapUpdateModeInterior" to if (fps == "60") {
                "oddsThenEvens, None, None"
            } else {
                "None, None, None"
            }
        )
        val scalarGraphicsValues = listOf(
            "AmbientOcclusion",
            "LightingQuality",
            "Mirrors",
            "Particles",
            "Skidmarks",
            "WeatherEffects"
        ).associateWith { key ->
            values.getValue("Graphics/$key").substringBefore(',').trim()
        }
        return GraphicsPreset(
            name,
            description,
            values + scalarGraphicsValues + mapOf(
                "VerticalSync" to "0",
                "ReduceVisibleRain" to "0"
            )
        )
    }
